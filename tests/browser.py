from playwright.sync_api import sync_playwright
import json
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':390,'height':844})
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:3000')
 page.get_by_role('button',name='＋ フォルダを作成').click()
 page.locator('#name').fill('学校')
 page.get_by_role('button',name='保存',exact=True).click()
 page.locator('[data-folder]').click()
 page.get_by_role('button',name='＋ ToDoを作成').click()
 page.locator('#name').fill('宿題')
 page.locator('#planned').fill('10')
 page.get_by_role('button',name='保存',exact=True).click()
 page.locator('[data-task]').click()
 page.get_by_role('button',name='スタート',exact=True).click()
 page.wait_for_timeout(1200)
 page.locator('[data-nav="home"]').click()
 page.get_by_role('button',name='◷ 計測中に戻る').click()
 page.reload()
 page.get_by_role('button',name='◷ 計測中に戻る').click()
 page.get_by_role('button',name='ストップ',exact=True).click()
 page.get_by_role('button',name='再開',exact=True).click()
 page.wait_for_timeout(1100)
 page.get_by_role('button',name='ストップ',exact=True).click()
 page.get_by_role('button',name='記録する',exact=True).click()
 assert page.locator('h2').filter(has_text='作業記録').count()==1
 state=page.evaluate("JSON.parse(localStorage.getItem('todo-v1'))")
 assert len(state['records'])==1 and state['timer'] is None
 page.locator('[data-nav="list"]').click()
 page.locator('[data-complete]').check()
 page.locator('[data-nav="result"]').click()
 assert '100%' in page.locator('main').inner_text()
 page.locator('[data-nav="home"]').click()
 page.get_by_role('button',name='＋ フォルダを作成').click()
 page.locator('#name').fill(' ')
 page.get_by_role('button',name='保存',exact=True).click()
 assert '1〜50文字' in page.locator('#form-error').inner_text()
 page.locator('#name').fill('未保存')
 page.get_by_role('button',name='キャンセル',exact=True).click()
 assert page.locator('#leave').is_visible()
 page.get_by_role('button',name='編集を続ける').click()
 assert page.locator('#name').input_value()=='未保存'
 page.get_by_role('button',name='キャンセル',exact=True).click()
 page.get_by_role('button',name='破棄して移動').click()
 page.screenshot(path='/workspace/ToDoリスト/docs/ホーム試作.png',full_page=True)
 assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
 # ファイル配下、フラグ順、検索、全件一覧
 page.locator('[data-folder]').click()
 page.get_by_role('button',name='＋ ファイル',exact=True).click()
 page.locator('#name').fill('英語')
 page.get_by_role('button',name='保存',exact=True).click()
 page.locator('[data-file]').click()
 for label,priority in [('単語',3),('試験対策',0)]:
  page.get_by_role('button',name='＋ ToDoを作成').click()
  page.locator('#name').fill(label)
  page.locator('#priority').select_option(str(priority))
  page.get_by_role('button',name='保存',exact=True).click()
 assert page.locator('[data-task]').first.inner_text().startswith('試験対策')
 page.locator('#search').fill('単語')
 assert page.locator('[data-task]').count()==1
 page.locator('[data-nav="result"]').click()
 assert '0 / 2件' in page.locator('main').inner_text()
 page.screenshot(path='/workspace/ToDoリスト/docs/結果試作.png',full_page=True)
 page.locator('[data-nav="home"]').click()
 page.get_by_role('button',name='全ToDoを見る').click()
 assert page.locator('[data-task]').count()==3
 # 容量不足時、入力を保持・永続状態を変更しない
 page.locator('[data-nav="home"]').click()
 page.get_by_role('button',name='＋ フォルダを作成').click()
 page.locator('#name').fill('保存失敗テスト')
 page.evaluate("() => {Storage.prototype.setItem=function(){throw new Error('容量不足')};}")
 page.get_by_role('button',name='保存',exact=True).click()
 assert page.locator('#editor').is_visible() and page.locator('#name').input_value()=='保存失敗テスト'
 assert '容量不足' in page.locator('#form-error').inner_text()
 assert not errors,errors
 print(json.dumps({'browser':'Chromium','viewport':'390x844','checks':['作成・階層・完了','計測開始停止再開保存','移動と再読込で計測保持','入力検証・未保存確認','並び順・検索・全件一覧','集計範囲','保存失敗時入力保持','横はみ出しなし'],'page_errors':errors},ensure_ascii=False,indent=2))
 browser.close()
